const catalogs: Record<string, Record<string, string>> = { pl: { ...pl } };
let lang: Lang = 'pl';

export function addCatalog(code: string, entries: Record<string, string>): void {
  catalogs[code] = { ...(catalogs[code] ?? {}), ...entries };
}

export function setLang(next: Lang): void {
  lang = next;
}

export function getLang(): Lang {
  return lang;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = catalogs[lang]?.[key] ?? catalogs.pl[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}
